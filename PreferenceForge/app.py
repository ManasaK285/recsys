import streamlit as st
import pandas as pd
from pathlib import Path
import json
from preferenceforge.config import FEATURES
from preferenceforge.collect import append_human_preference

st.set_page_config(page_title="PreferenceForge", layout="wide")
st.title("PreferenceForge")
st.caption("Personalized reward modeling from pairwise human preferences")

tab1, tab2, tab3 = st.tabs(["Compare responses", "Model evaluation", "User reward profile"])

with tab1:
    st.subheader("Collect a pairwise preference")
    uid = st.text_input("User ID", value="human_001")
    prompt = st.text_area("Prompt", "Explain how a hash table works.")
    c1, c2 = st.columns(2)
    with c1:
        st.markdown("**Response A**")
        response_a = st.text_area("A text", "A hash table maps keys to values using a hash function.", key="a")
    with c2:
        st.markdown("**Response B**")
        response_b = st.text_area("B text", "A hash table is a data structure. First, a hash function transforms a key into an index. Collisions can be handled with chaining or open addressing. Average lookup is often O(1), though worst-case behavior can be slower.", key="b")
    st.caption("Rate each candidate's observable qualities. These are human-entered feature annotations, not automatically inferred truths.")
    left, right = st.columns(2)
    a_feats, b_feats = {}, {}
    for f in FEATURES:
        with left: a_feats[f] = st.slider(f"A · {f}", 0.0, 1.0, 0.6, 0.05, key="a_"+f)
        with right: b_feats[f] = st.slider(f"B · {f}", 0.0, 1.0, 0.7, 0.05, key="b_"+f)
    label = st.radio("Which response do you prefer?", ["A", "B"], horizontal=True)
    if st.button("Save preference", type="primary"):
        path = append_human_preference(uid, prompt, response_a, response_b, a_feats, b_feats, int(label == "A"))
        st.success(f"Saved comparison to {path}")

with tab2:
    metrics_path = Path("artifacts/metrics.csv")
    if metrics_path.exists():
        df = pd.read_csv(metrics_path)
        st.dataframe(df, use_container_width=True)
        st.bar_chart(df.set_index("model")[["accuracy"]])
        st.caption("Metrics are generated by your local experiment; synthetic-data results should not be represented as real human preference results.")
    else:
        st.info("Run `python -m preferenceforge.cli all` to generate data, train models, and evaluate them.")

with tab3:
    path = Path("artifacts/models.json")
    if path.exists():
        payload = json.loads(path.read_text())
        models = payload.get("models", {})
        selected = st.selectbox("Model", list(models.keys()))
        user_ids = list(models[selected].keys())
        if user_ids:
            uid2 = st.selectbox("User", user_ids)
            weights = models[selected][uid2]
            st.write(pd.DataFrame({"feature": FEATURES, "weight": weights}))
            st.bar_chart(pd.DataFrame({"weight": weights}, index=FEATURES))
        else:
            st.info("This model export contains no per-user weights.")
    else:
        st.info("Train models first.")
